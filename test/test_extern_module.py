"""The extern escape hatch: wrap a hand-written kernel with the same checks."""
from pathlib import Path

import pytest

from compiler.extern import ExternModule, ExternModuleError, assemble

KERNELS = '''@triton.jit
def add_kernel(x_ptr, y_ptr, n, BLOCK: tl.constexpr):
    pid = tl.program_id(0)
    offsets = pid * BLOCK + tl.arange(0, BLOCK)
    mask = offsets < n
    tl.store(y_ptr + offsets, tl.load(x_ptr + offsets, mask=mask) + 1.0, mask=mask)
'''
HOST = '''def add_one(x):
    y = torch.empty_like(x)
    add_kernel[(triton.cdiv(x.numel(), 1024),)](x, y, x.numel(), BLOCK=1024)
    return y
'''


def test_a_hand_written_kernel_gets_the_generated_module_envelope(tmp_path):
    text = assemble(ExternModule(name='add_one', doc='adds one', kernels=KERNELS,
                                 host=HOST, provenance='unit-test'))
    assert text.startswith('# Generated by FlowGPU (extern escape hatch).')
    assert 'NOT emitted by the compiler' in text
    assert 'content-sha256:' in text
    assert '@triton.jit' in text and 'def add_one(x):' in text
    compile(text, '<extern>', 'exec')
    path = tmp_path / 'add_one.py'
    path.write_text(text)
    assert path.read_text() == text


def test_an_unparseable_piece_is_rejected_before_it_becomes_a_submission():
    with pytest.raises(ExternModuleError, match='does not parse'):
        assemble(ExternModule(name='add_one', doc='', kernels='def broken(:',
                              host=HOST, provenance='unit-test'))


def test_a_kernel_without_a_jit_function_is_rejected():
    with pytest.raises(ExternModuleError, match='@triton.jit'):
        assemble(ExternModule(name='add_one', doc='', kernels='x = 1',
                              host=HOST, provenance='unit-test'))


def test_a_host_without_the_named_entry_point_is_rejected():
    with pytest.raises(ExternModuleError, match='named'):
        assemble(ExternModule(name='add_one', doc='', kernels=KERNELS,
                              host='def not_the_entry(x):\n    return x\n',
                              provenance='unit-test'))


def test_kernel_and_host_cannot_shadow_each_other():
    host = 'def add_kernel(x):\n    return x\n\n' + HOST
    with pytest.raises(ExternModuleError, match='same top-level names'):
        assemble(ExternModule(name='add_one', doc='', kernels=KERNELS,
                              host=host, provenance='unit-test'))
