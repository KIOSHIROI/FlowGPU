"""Opt-in structural deduplication of compiler-owned fixed native modules.

Kernel identity includes the complete AST except its public name. Hosts may
share a body only when they differ in names, docstrings and torch dtype
constants; those constants remain fixed per typed entry, not inferred at run
time. No eval, device arithmetic fallback, or removal of runtime guards.
"""
import ast
import copy

DTYPES = {'float16', 'bfloat16', 'float32', 'int32', 'int64', 'bool'}


def compact_source(source, *, profile='row-gather'):
    if profile not in {'row-gather', 'fixed-native'}:
        raise ValueError('unknown compaction profile')
    tree = ast.parse(source)
    definitions = [n.name for n in tree.body if isinstance(n, ast.FunctionDef)]
    if len(definitions) != len(set(definitions)):
        raise ValueError('compaction requires unique function names')
    if any(name == '_fg_bind' or name.startswith('_fg_host_') for name in definitions):
        raise ValueError('compaction helper name collision')
    if any(a.arg.startswith('_fg_dtype_') for n in tree.body if isinstance(n, ast.FunctionDef)
           for a in (*n.args.posonlyargs, *n.args.args, *n.args.kwonlyargs)):
        raise ValueError('compaction dtype binding name collision')
    kernels = {}; aliases = {}; output = []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.decorator_list:
            normal = copy.deepcopy(node); normal.name = '_kernel'
            key = ast.dump(normal, include_attributes=False)
            if key in kernels:
                aliases[node.name] = kernels[key]
            else:
                kernels[key] = node.name
                output.append(node)
        else:
            output.append(node)

    class Rename(ast.NodeTransformer):
        def visit_Name(self, node):
            if node.id in aliases:
                node.id = aliases[node.id]
            return node

    tree.body = [Rename().visit(n) for n in output]
    hosts = {}; output = []; bindings = []
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef) or not node.name.startswith('run_'):
            output.append(node); continue
        original_name = node.name
        normal = copy.deepcopy(node); normal.name = '_host'
        if (normal.body and isinstance(normal.body[0], ast.Expr)
                and isinstance(normal.body[0].value, ast.Constant)
                and isinstance(normal.body[0].value.value, str)):
            normal.body.pop(0)
        values = []

        class Parameterize(ast.NodeTransformer):
            def visit_Attribute(self, item):
                if (isinstance(item.value, ast.Name) and item.value.id == 'torch'
                        and item.attr in DTYPES):
                    name = '_fg_dtype_' + str(len(values))
                    values.append(copy.deepcopy(item))
                    return ast.copy_location(ast.Name(id=name, ctx=ast.Load()), item)
                return self.generic_visit(item)

        normal = Parameterize().visit(normal)
        key = ast.dump(normal, include_attributes=False)
        if key not in hosts:
            normal.name = '_fg_host_' + str(len(hosts))
            hosts[key] = normal.name
            normal.args.kwonlyargs.extend(ast.arg(arg='_fg_dtype_' + str(i)) for i in range(len(values)))
            normal.args.kw_defaults.extend([None] * len(values))
            output.append(normal)
        bindings.append(ast.Assign(targets=[ast.Name(id=original_name, ctx=ast.Store())],
            value=ast.Call(func=ast.Name(id='_fg_bind', ctx=ast.Load()),
                args=[ast.Name(id=hosts[key], ctx=ast.Load()), ast.Tuple(elts=values, ctx=ast.Load())], keywords=[])))
    if bindings:
        output.extend(ast.parse('''
def _fg_bind(host, dtypes):
    bound = {'_fg_dtype_' + str(i): value for i, value in enumerate(dtypes)}
    def run(*args, **kwargs):
        return host(*args, **kwargs, **bound)
    return run
''').body)
        output.extend(bindings)
    tree.body = output
    ast.fix_missing_locations(tree)
    return f'# Generated by FlowGPU; structurally compacted {profile} module.\n' + ast.unparse(tree) + '\n'
