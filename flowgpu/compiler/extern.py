"""Escape hatch for hand-written Triton kernels.

Why this exists
---------------
The FlowGPU frontend is a closed tensor-operator language: it names the
operators it can lower, and everything else is a refusal.  That is what makes
generated modules verifiable, variant-cheap and reproducible, but it also means
a kernel that needs control the operator set does not expose -- a decoupled
scan, a TMA pipeline, warp specialisation, a packed layout with a hand-designed
bank-conflict pattern -- cannot be expressed without editing the flowgpu.compiler.  The
2026-10-26 competition runs showed the cost of treating every such kernel as a
compiler-feature request: `matmul_v2` went from 578.8 us to 241.6 us only after
the GEMM was written by hand, while several hours went into one-operator
generator patches.

This module is the deliberate alternative.  It wraps an author-supplied Triton
kernel and host glue in the *same* module envelope the compiler emits: standard
banner, import prelude, a provenance line, a content hash, and structural
validation (the text must parse, the kernel source must define at least one
``@triton.jit`` function, the host source must define a callable, and the two
must not share top-level names).  It does not pretend the kernel was generated;
provenance says so explicitly.

The rule for promoting an extern kernel back into the language: at least two
independent tasks must need the same construct.  One task is a kernel; two
tasks are a feature.

Host-glue rules (learned on Ascend, 2026-10-26)
----------------------------------------------
The 910C harness failed `torch.zeros` and `.contiguous()`-style inplace copies
with `aclnnInplaceZero` / `aclnnInplaceCopy` error 561103, while `torch.empty`
allocations and Triton kernels worked.  Extern hosts should therefore:

* allocate with `torch.empty` / `torch.empty_like` only;
* zero or copy with a small Triton kernel instead of `torch.zeros`, `.clone()`
  or `.contiguous()` on the device (a `contiguous()` call on an already
  contiguous tensor is free, but a real copy is not);
* keep all arithmetic in the supplied kernels -- the host is glue, not compute.

Usage
-----
    from flowgpu.compiler.extern import ExternModule, assemble

    text = assemble(ExternModule(
        name="matmul_tuned",
        doc="128x256x32 grouped GEMM, measured 241.6 us on H100",
        kernels=open("kernel.py").read(),
        host=open("host.py").read(),
        provenance="gpu-mode/matmul_v2 2026-10-26",
    ))
    Path("submission.py").write_text(text)
"""

from __future__ import annotations

import ast
import hashlib
from dataclasses import dataclass

__all__ = ['ExternModule', 'assemble', 'ExternModuleError']


class ExternModuleError(ValueError):
    """The supplied kernel/host text is not a usable module."""


@dataclass(frozen=True)
class ExternModule:
    """One hand-written kernel family wrapped for the compiler's pipelines."""

    name: str
    doc: str
    kernels: str
    host: str
    provenance: str
    imports: tuple = ('import torch', 'import triton',
                       'import triton.language as tl')


BANNER = '''# Generated by FlowGPU (extern escape hatch).
#
# The Triton kernel in this file was NOT emitted by the compiler.  It is a
# hand-written kernel that the FlowGPU escape hatch wrapped so that provenance,
# hashing and the structural checks are the same as for generated modules.
# Rule for promoting it into the language: at least two independent tasks need
# the same construct.
#
# provenance: {provenance}
# content-sha256: {sha}
'''

TAIL = '''

def module_sha256() -> str:
    """Hash of the kernel+host payload (not of this wrapper's banner)."""
    return {sha!r}
'''


def _top_level_functions(tree: ast.Module) -> dict:
    return {node.name: node for node in tree.body
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))}


def _jit_functions(tree: ast.Module) -> list:
    found = []
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef):
            continue
        for decorator in node.decorator_list:
            target = decorator.func if isinstance(decorator, ast.Call) else decorator
            name = getattr(target, 'attr', None) or getattr(target, 'id', None)
            if name == 'jit':
                found.append(node.name)
    return found


def assemble(module: ExternModule, *, strict=True) -> str:
    """Validate the hand-written pieces and return the full module text.

    ``strict`` also rejects shadowed names: a kernel and a host function with
    the same name is always a typo, and it would fail only at import time on the
    device.  The generated text is validated with ``ast.parse`` before it is
    returned; a source that cannot be parsed never reaches a submission.
    """
    if not module.name.isidentifier():
        raise ExternModuleError(f'extern module name is not an identifier: {module.name!r}')
    if not module.provenance.strip():
        raise ExternModuleError('extern module needs a provenance string')
    for label, text in (('kernels', module.kernels), ('host', module.host)):
        if not text.strip():
            raise ExternModuleError(f'extern module has no {label} source')
        try:
            ast.parse(text)
        except SyntaxError as error:
            raise ExternModuleError(f'extern {label} source does not parse: {error}') from error
    kernel_tree = ast.parse(module.kernels)
    host_tree = ast.parse(module.host)
    kernels = _top_level_functions(kernel_tree)
    hosts = _top_level_functions(host_tree)
    jit_names = _jit_functions(kernel_tree)
    if not jit_names:
        raise ExternModuleError('extern kernels source defines no @triton.jit function')
    if strict:
        shared = sorted(set(kernels) & set(hosts))
        if shared:
            raise ExternModuleError(
                'kernel and host define the same top-level names: %s' % shared)
    if not any(name == module.name for name in hosts):
        raise ExternModuleError(
            f'extern host source must define a callable named {module.name!r}')
    payload = (module.kernels + '\n' + module.host).encode()
    sha = hashlib.sha256(payload).hexdigest()
    banner = BANNER.format(provenance=module.provenance.strip(), sha=sha)
    parts = [banner, '', f'"""FlowGPU extern module: {module.name}.', '',
             module.doc.strip(), '"""', '']
    parts.extend(module.imports)
    parts.extend(['', '', module.kernels.rstrip(), '', '', module.host.rstrip(), '',
                  TAIL.format(sha=sha)])
    text = '\n'.join(parts).rstrip() + '\n'
    try:
        ast.parse(text)
    except SyntaxError as error:  # pragma: no cover - assemble() built it
        raise ExternModuleError(f'assembled module does not parse: {error}') from error
    return text
